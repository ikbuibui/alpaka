"""Build the isolated mapping engine and static site; no Sphinx or project CMake needed."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
from urllib.parse import urlparse
from urllib.request import Request, urlopen

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BUILD = HERE / "build"
DEFAULT_HEADER_URL = "https://alpaka.readthedocs.io/en/latest/alpaka.hpp"


def run(command):
    """Print and run a checked command from the repository root."""
    print("+", " ".join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), cwd=ROOT, check=True)


def fingerprint():
    """Hash local headers and adapter build inputs in a reproducible order."""
    digest = hashlib.sha256()
    for path in sorted((ROOT / "include").rglob("*.hpp"), key=str) + [
        HERE / "engine.cpp",
        HERE / "build.py",
        HERE / "validate_backend.cpp",
    ]:
        digest.update(str(path.relative_to(ROOT)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def options():
    """Parse build options and check the requested toolchains."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cxx", default=os.environ.get("CXX", "c++"))
    parser.add_argument("--emxx", default=os.environ.get("EMXX", "em++"))
    parser.add_argument("--native-only", action="store_true")
    parser.add_argument(
        "--single-header", action="store_true", help="Generate the Godbolt HTTP-include export and references"
    )
    parser.add_argument(
        "--godbolt-header-url", default=DEFAULT_HEADER_URL, help="Public HTTP(S) single-header URL for Godbolt"
    )
    parser.add_argument(
        "--validate-http-header", action="store_true", help="Also fetch and compile the actual Godbolt URL header"
    )
    parser.add_argument(
        "--cuda", action="store_true", help="Also compile the real CUDA backend validator (GPU optional)"
    )
    parser.add_argument("--nvcc", default=os.environ.get("NVCC", "nvcc"))
    args = parser.parse_args()
    if not args.native_only and not shutil.which(args.emxx):
        parser.error("em++ not found. Activate emsdk or pass --emxx /path/to/em++; see README.md")
    if args.cuda and not shutil.which(args.nvcc):
        parser.error("nvcc not found. Pass --nvcc /path/to/nvcc or leave out --cuda")
    url = urlparse(args.godbolt_header_url)
    if (
        url.scheme not in ("http", "https")
        or not url.netloc
        or any(char.isspace() or char in '<>"\\' for char in args.godbolt_header_url)
    ):
        parser.error("--godbolt-header-url must be an HTTP(S) URL usable in an angle-bracket include")
    if args.validate_http_header and not args.single_header:
        parser.error("--validate-http-header requires --single-header")
    return args


def compile_cuda(args, source, output, flags):
    """Require real CUDA mode, including when the source has a .cpp extension."""
    run(
        [
            args.nvcc,
            "-x",
            "cu",
            *flags,
            "-ccbin",
            args.cxx,
            "-Xcompiler=-pthread",
            "--expt-relaxed-constexpr",
            "--extended-lambda",
            "-DALPAKA_MAPPING_REQUIRE_CUDA",
            source,
            "-o",
            output,
        ]
    )


def compile_resolved_export(args, source, stem):
    """Compile a locally resolved HTTP-include export with ordinary native compilers."""
    run([args.cxx, "-std=c++20", "-O1", "-pthread", source, "-o", BUILD / f"{stem}-cpu"])
    if args.cuda:
        compile_cuda(args, source, BUILD / f"{stem}-cuda", ["-std=c++20", "-O1"])


def clear_godbolt(site):
    """Remove only generated Godbolt artifacts, including optional HTTP references."""
    for pattern in (
        "validate-godbolt-*",
        "godbolt-validation*.cpp",
        "godbolt-header-http.hpp",
        "mapping-single-header",
    ):
        for path in BUILD.glob(pattern):
            path.unlink()
    (site / "godbolt-validation.cpp").unlink(missing_ok=True)


def build_godbolt(args, flags, provenance, site):
    """Export an HTTP include; test local and optionally fetched-header resolutions separately."""
    header_dir = BUILD / "single-header"
    run(["bash", ROOT / "script/create-single-header.sh", header_dir])
    run(
        [
            args.cxx,
            *flags,
            "-DALPAKA_MAPPING_SINGLE_HEADER",
            "-I",
            header_dir,
            HERE / "engine.cpp",
            "-o",
            BUILD / "mapping-single-header",
        ]
    )
    include = f"#include <{args.godbolt_header_url}>"
    preamble = (
        "// Generated by tools/index-mapping/build.py --single-header.\n"
        f"// Explorer checkout: {provenance}\n"
        "// Godbolt uses the URL below, NOT necessarily this checkout (especially with uncommitted changes).\n"
        "// CPU: -std=c++20 -O1 -pthread\n"
        "// CUDA: -x cu -std=c++20 -O1 --expt-relaxed-constexpr --extended-lambda\n"
        "#define ALPAKA_DISABLE_STD_SIMD\n#define ALPAKA_DISABLE_TBB\n#define ALPAKA_DISABLE_HWLOC\n"
        "#define ALPAKA_MAPPING_EMBEDDED\n#define ALPAKA_MAPPING_NO_MAIN\n"
        f'#define ALPAKA_MAPPING_BUILD "{provenance}"\n'
    )
    body = (
        preamble
        + include
        + "\n"
        + (HERE / "engine.cpp").read_text()
        + "\n"
        + (HERE / "validate_backend.cpp").read_text()
    )
    export = BUILD / "godbolt-validation.cpp"
    export.write_text(body)
    shutil.copy2(export, site / export.name)
    # Native compilers do not implement Compiler Explorer's HTTP include preprocessing.
    # Resolve that one include to the current tree's generated header for the normal CI reference.
    local = BUILD / "godbolt-validation-local.cpp"
    local.write_text(body.replace(include, (header_dir / "alpaka.hpp").read_text(), 1))
    compile_resolved_export(args, local, "validate-godbolt")
    if not args.validate_http_header:
        return None
    # An explicitly requested second reference checks what Godbolt will actually download.
    # Keep this opt-in: a published header may legitimately lag unmerged changes in a PR.
    print(f"Fetching Godbolt header: {args.godbolt_header_url}", flush=True)
    request = Request(args.godbolt_header_url, headers={"User-Agent": "alpaka-index-mapping-validator/1.0"})
    with urlopen(request, timeout=30) as response:
        data = response.read(10 * 1024 * 1024 + 1)
    if len(data) > 10 * 1024 * 1024:
        raise ValueError("Godbolt header exceeds the 10 MiB download limit")
    (BUILD / "godbolt-header-http.hpp").write_bytes(data)
    remote = BUILD / "godbolt-validation-http.cpp"
    remote.write_text(body.replace(include, data.decode("utf-8"), 1))
    compile_resolved_export(args, remote, "validate-godbolt-http")
    return hashlib.sha256(data).hexdigest()


def main():
    """Compile the requested engines and assemble the standalone site."""
    args = options()
    BUILD.mkdir(exist_ok=True)
    site = BUILD / "site"
    site.mkdir(exist_ok=True)
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    source_hash = fingerprint()
    provenance = f"{revision[:12]} / {source_hash[:16]}"
    flags = [
        "-std=c++20",
        "-O1",
        "-DALPAKA_DISABLE_STD_SIMD",
        "-DALPAKA_DISABLE_TBB",
        "-DALPAKA_DISABLE_HWLOC",
        f'-DALPAKA_MAPPING_BUILD="{provenance}"',
    ]
    source = HERE / "engine.cpp"
    run([args.cxx, *flags, "-I", ROOT / "include", source, "-o", BUILD / "mapping-native"])
    run(
        [
            args.cxx,
            *flags,
            "-pthread",
            "-I",
            ROOT / "include",
            HERE / "validate_backend.cpp",
            "-o",
            BUILD / "validate-cpu",
        ]
    )
    if args.cuda:
        compile_cuda(args, HERE / "validate_backend.cpp", BUILD / "validate-cuda", [*flags, "-I", ROOT / "include"])
    else:
        (BUILD / "validate-cuda").unlink(missing_ok=True)
    clear_godbolt(site)
    http_hash = build_godbolt(args, flags, provenance, site) if args.single_header else None
    if not args.native_only:
        run(
            [
                args.emxx,
                *flags,
                "-I",
                ROOT / "include",
                source,
                "--no-entry",
                "-fexceptions",
                "-sMODULARIZE=1",
                "-sEXPORT_ES6=1",
                "-sENVIRONMENT=web,node",
                "-sALLOW_MEMORY_GROWTH=1",
                "-sFILESYSTEM=0",
                '-sEXPORTED_FUNCTIONS=["_mapping_trace"]',
                '-sEXPORTED_RUNTIME_METHODS=["ccall"]',
                "-o",
                site / "engine.mjs",
            ]
        )
    else:
        for path in (site / "engine.mjs", site / "engine.wasm"):
            path.unlink(missing_ok=True)
    for path in (HERE / "web").iterdir():
        if path.is_file():
            shutil.copy2(path, site / path.name)
    manifest = {
        "revision": revision,
        "sourceHash": source_hash,
        "build": provenance,
        "wasm": not args.native_only,
        "singleHeader": args.single_header,
        "cudaCompiled": args.cuda,
        "godboltHeaderUrl": args.godbolt_header_url if args.single_header else None,
        "godboltHttpCompiled": http_hash is not None,
        "godboltHttpHeaderSha256": http_hash,
        "scope": (
            "Synthetic worker contexts; Vec/CVec FrameSpec resolution for an assumed device profile; "
            "no backend execution"
        ),
    }
    (BUILD / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (site / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("\nTest:  node tools/index-mapping/test.mjs")
    print("Serve: python3 -m http.server 8000 --bind 127.0.0.1 --directory tools/index-mapping/build/site")


if __name__ == "__main__":
    main()
